"""
Програма для перевірки, чи є введений рядок паліндромом.
Паліндром — це слово, фраза або текст, який однаково читається 
як зліва направо, так і справа наліво (наприклад, "шалаш" або "А роза упала на лапу Азора").
"""

def is_palindrome(text_to_check: str) -> bool:
    """
    Перевіряє, чи є переданий рядок паліндромом,
    ігноруючи регістр літер та пробіли.
    
    Аргументи:
        text_to_check (str): Рядок, який потрібно перевірити.
        
    Повертає:
        bool: True, якщо рядок є паліндромом, і False в іншому випадку.
    """
    # 1. Крок нормалізації: переводимо текст у нижній регістр та прибираємо пробіли
    cleaned_text = "".join(text_to_check.lower().split())
    
    # 2. Створюємо обернену копію очищеного рядка за допомогою зрізу [::-1]
    reversed_text = cleaned_text[::-1]
    
    # 3. Логіка перевірки: порівнюємо оригінальний очищений рядок з перевернутим
    is_match = (cleaned_text == reversed_text)
    
    return is_match


if __name__ == "__main__":
    # Приклад перевірки роботи програми
    user_string = "А роза упала на лапу Азора"
    
    if is_palindrome(user_string):
        print(f"'{user_string}' — це паліндром!")
    else:
        print(f"'{user_string}' — це не паліндром.")
